"""Tests for tools/check_ci_locks.py, each with a planted defect: python tools/test_check_ci_locks.py"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import check_ci_locks as c  # noqa: E402

BASE, EXTRAS = {"cryptography"}, {"mcp": {"mcp"}, "test": {"pytest", "anyio"}}
IN = "# extras: mcp, test\ncryptography>=42\nmcp==2.3.0\npytest>=8\nanyio>=4\n"
HEADER = "# This file was autogenerated by uv via the following command:\n#    uv pip compile --universal --python-version 3.10 --generate-hashes ci/x.in -o ci/x.txt\n"


def lock(*names: str) -> str:
    return HEADER + "".join(f"{n}==1.0 \\\n    --hash=sha256:{'a' * 64}\n    # via -r ci/x.in\n" for n in names)


class CheckTests(unittest.TestCase):
    def test_this_repo_passes(self):
        self.assertEqual(c.main(), 0)

    def test_complete_in_and_lock_pass(self):
        self.assertEqual(c.check_in(IN, BASE, EXTRAS), [])
        self.assertEqual(c.check_txt(lock("cryptography", "mcp", "pytest", "anyio"), IN), [])

    def test_in_missing_an_extra_dependency(self):
        errors = c.check_in(IN.replace("anyio>=4\n", ""), BASE, EXTRAS)
        self.assertEqual(errors, ["missing anyio (SDK dependency or extra)"])

    def test_in_naming_an_unknown_extra(self):
        self.assertIn("unknown extra 'nope'", c.check_in(IN.replace("test", "nope", 1), BASE, EXTRAS))

    def test_lock_pin_without_hash(self):
        txt = lock("cryptography", "mcp", "pytest") + "anyio==4.0\n"
        self.assertEqual(c.check_txt(txt, IN), ["no sha256 hash for anyio==4.0"])

    def test_lock_missing_a_pin_or_compiled_without_hashes(self):
        self.assertIn("anyio is in the .in file but not pinned (relock)", c.check_txt(lock("cryptography", "mcp", "pytest"), IN))
        txt = lock("cryptography", "mcp", "pytest", "anyio").replace(" --generate-hashes", "")
        self.assertEqual(c.check_txt(txt, IN), ["header lacks '--generate-hashes' (relock with the command in the .in file)"])

    def test_lock_with_a_range_or_url(self):
        self.assertTrue(c.check_txt(lock("cryptography", "mcp", "pytest", "anyio") + "evil>=1\n", IN))
        self.assertTrue(c.check_txt(lock("cryptography", "mcp", "pytest", "anyio") + "evil @ https://x/y.whl\n", IN))

    def test_workflow_pip_forms(self):
        ok = [
            "run: python -m pip install --require-hashes -r ci/test.txt",
            "run: python -m pip install --no-deps dist/*.whl",
            "run: python -m pip install --require-hashes -r ci/a.txt && python -m pip install --no-deps dist/*.whl",
        ]
        bad = [
            'run: python -m pip install "build>=1.2"',
            "run: python -m pip install ./sdk/python[test]",
            "run: python -m pip install -r ci/test.txt",
            "run: python -m pip install --no-deps dist/*.whl pytest",
            "run: pip install --require-hashes pytest",
        ]
        for line in ok:
            self.assertEqual(c.check_workflow(line), [], line)
        for line in bad:
            self.assertTrue(c.check_workflow(line), line)


if __name__ == "__main__":
    unittest.main()
